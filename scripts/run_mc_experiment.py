#!/usr/bin/env python3
"""
run_mc_experiment.py — Reproducible Monte Carlo experiment runner for DIPLOMA.

Calls POST /api/v1/simulator/monte_carlo, saves three artifact files:
  <prefix>_full.json   — raw API response
  <prefix>_runs.csv    — per-run flat CSV with compact model reference columns
  <prefix>_meta.json   — experiment metadata with full model_config reproducibility block

Reproducibility linkage:
  If results/dependency_matrix_live_snapshot.json exists, it is used as the
  canonical model_config source and its path is recorded in meta.json.
  If it does not exist, the live matrix is fetched from risk_engine, the
  snapshot is created, and then linked.

Usage:
  python scripts/run_mc_experiment.py --help
  python scripts/run_mc_experiment.py --scenario S1_energy_outage --sector energy \
      --runs 100 --stochastic-scale 0.3 --prefix results/mc_s1_100
"""

import argparse
import csv
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import httpx

# ---------------------------------------------------------------------------
# Defaults
# ---------------------------------------------------------------------------
SIMULATOR_URL = os.getenv("SIMULATOR_URL", "http://localhost:8005")
RISK_ENGINE_URL = os.getenv("RISK_ENGINE_URL", "http://localhost:8004")
SNAPSHOT_PATH = Path("results/dependency_matrix_live_snapshot.json")

# Compact reference columns added to every CSV row
CSV_MODEL_COLS = ["matrix_version", "theta_bin", "theta_cascade"]


# ---------------------------------------------------------------------------
# Snapshot helpers
# ---------------------------------------------------------------------------

def _fetch_live_snapshot() -> dict:
    """Fetch matrix, weights, and thresholds from live risk_engine and return snapshot dict."""
    with httpx.Client(timeout=10.0) as client:
        mat_resp = client.get(f"{RISK_ENGINE_URL}/api/v1/risk/dependency_matrix")
        mat_resp.raise_for_status()
        mat_data = mat_resp.json()

        thr_resp = client.get(f"{RISK_ENGINE_URL}/api/v1/risk/classical_threshold")
        thr_resp.raise_for_status()
        thr_data = thr_resp.json()

    matrix = mat_data.get("matrix", [])
    version = mat_data.get("version", "unknown")
    sectors_order = mat_data.get("sectors_order", ["energy", "water", "transport"])
    weights = mat_data.get("sector_weights", {"energy": 0.4, "water": 0.3, "transport": 0.3})
    theta_bin = float(thr_data.get("theta_bin", 0.70))

    snapshot = {
        "snapshot_metadata": {
            "created_at": datetime.now(tz=timezone.utc).isoformat(),
            "source": "live API — DIPLOMA risk_engine",
            "source_endpoints": [
                f"GET {RISK_ENGINE_URL}/api/v1/risk/dependency_matrix",
                f"GET {RISK_ENGINE_URL}/api/v1/risk/classical_threshold",
            ],
            "note": "Auto-generated by run_mc_experiment.py at experiment time.",
        },
        "dependency_matrix": {
            "version": version,
            "sectors_order": sectors_order,
            "matrix": matrix,
            "matrix_semantics": (
                "A[i][j] = influence of sector j (SOURCE) on sector i (DESTINATION)."
            ),
            "source": f"GET {RISK_ENGINE_URL}/api/v1/risk/dependency_matrix",
        },
        "sector_weights": weights,
        "classical_threshold": {
            "theta_bin": theta_bin,
            "active_edges": thr_data.get("active_edges", []),
            "inactive_edges": thr_data.get("inactive_edges", []),
            "source": f"GET {RISK_ENGINE_URL}/api/v1/risk/classical_threshold",
        },
        "theta_cascade": {
            "value": 0.3,
            "source": "schemas.py MonteCarloRequest default",
        },
    }
    return snapshot


def load_or_create_snapshot(snapshot_path: Path, force_refresh: bool = False) -> dict:
    """Return snapshot dict; create/overwrite snapshot file if needed."""
    if snapshot_path.exists() and not force_refresh:
        print(f"[snapshot] Using existing snapshot: {snapshot_path}")
        with open(snapshot_path) as f:
            return json.load(f)

    print(f"[snapshot] Fetching live matrix from {RISK_ENGINE_URL} ...")
    snapshot = _fetch_live_snapshot()
    snapshot_path.parent.mkdir(parents=True, exist_ok=True)
    with open(snapshot_path, "w") as f:
        json.dump(snapshot, f, indent=2)
    print(f"[snapshot] Saved snapshot → {snapshot_path}")
    return snapshot


def build_model_config(snapshot: dict, snapshot_path: Path) -> dict:
    """Extract the minimal reproducibility block from a snapshot dict."""
    dep = snapshot.get("dependency_matrix", {})
    weights_raw = snapshot.get("sector_weights", {})
    # sector_weights may be a dict directly or contain extra keys
    weights = {k: v for k, v in weights_raw.items() if isinstance(v, (int, float))}
    thr = snapshot.get("classical_threshold", {})
    tc = snapshot.get("theta_cascade", {})

    return {
        "matrix_snapshot_path": str(snapshot_path),
        "matrix_version": dep.get("version", "unknown"),
        "sectors_order": dep.get("sectors_order", ["energy", "water", "transport"]),
        "dependency_matrix": dep.get("matrix", []),
        "sector_weights": weights,
        "theta_bin": thr.get("theta_bin", 0.25),
        "theta_cascade": tc.get("value", 0.3),
        "snapshot_source": snapshot.get("snapshot_metadata", {}).get("source", ""),
        "snapshot_created_at": snapshot.get("snapshot_metadata", {}).get("created_at", ""),
    }


# ---------------------------------------------------------------------------
# MC run
# ---------------------------------------------------------------------------

def run_mc(payload: dict, simulator_url: str) -> dict:
    """POST to monte_carlo endpoint; return parsed JSON response."""
    url = f"{simulator_url}/api/v1/simulator/monte_carlo"
    print(f"[mc] POST {url}  runs={payload.get('runs')}")
    with httpx.Client(timeout=600.0) as client:
        resp = client.post(url, json=payload)
        resp.raise_for_status()
    return resp.json()


# ---------------------------------------------------------------------------
# Artifact helpers
# ---------------------------------------------------------------------------

def _flatten_run(run: dict, model_config: dict) -> dict:
    """Flatten a single MC run dict into a CSV-ready flat row."""
    flat = {}
    for k, v in run.items():
        if isinstance(v, (list, dict)):
            flat[k] = json.dumps(v, ensure_ascii=False)
        else:
            flat[k] = v

    # Append compact model reference columns
    flat["matrix_version"] = model_config["matrix_version"]
    flat["theta_bin"] = model_config["theta_bin"]
    flat["theta_cascade"] = model_config["theta_cascade"]
    return flat


def save_artifacts(
    result: dict,
    model_config: dict,
    request_payload: dict,
    prefix: str,
    elapsed: float,
    simulator_url: str,
) -> dict:
    """Save _full.json, _runs.csv, _meta.json; return paths dict."""
    prefix_path = Path(prefix)
    prefix_path.parent.mkdir(parents=True, exist_ok=True)

    full_path = Path(f"{prefix}_full.json")
    csv_path = Path(f"{prefix}_runs.csv")
    meta_path = Path(f"{prefix}_meta.json")

    # 1. Full JSON
    with open(full_path, "w") as f:
        json.dump(result, f, indent=2, ensure_ascii=False)
    print(f"[save] full JSON → {full_path}")

    # 2. CSV with model reference columns
    runs_data = result.get("runs_data", [])
    if runs_data:
        all_rows = [_flatten_run(r, model_config) for r in runs_data]
        fieldnames = list(all_rows[0].keys())
        with open(csv_path, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(all_rows)
        print(f"[save] CSV ({len(runs_data)} runs) → {csv_path}")
    else:
        print("[save] No runs_data — CSV skipped")

    # 3. Meta JSON with model_config reproducibility block
    aggregate_stats = {
        k: result.get(k)
        for k in ("mean_delta", "std_delta", "min_delta", "max_delta", "p95_delta",
                  "K_q", "K_cl", "Delta_percent", "duration_correlation")
        if k in result
    }
    aggregate_stats["runs"] = result.get("runs", request_payload.get("runs"))

    theta_cascade_val = request_payload.get("theta_classical", model_config["theta_cascade"])

    meta = {
        "experiment_timestamp": datetime.now(tz=timezone.utc).isoformat(),
        "total_runtime_seconds": round(elapsed, 2),
        "endpoint": f"{simulator_url}/api/v1/simulator/monte_carlo",
        "request_payload": request_payload,
        "model_config": model_config,
        "risk_engine_config": {
            "theta_bin": model_config["theta_bin"],
            "theta_bin_default": 0.25,
        },
        "aggregate_stats": aggregate_stats,
        "research_mode_notes": {
            "stochastic_scale": request_payload.get("stochastic_scale", 0.0),
            "stochastic_meaning": "dependency_multiplier ~ max(0, N(1, stochastic_scale)) per run",
            "theta_bin": model_config["theta_bin"],
            "theta_cascade": theta_cascade_val,
            "duration_range": (
                f"[{request_payload.get('duration_min', '?')},"
                f"{request_payload.get('duration_max', '?')}] min"
            ),
            "matrix_version": model_config["matrix_version"],
            "reproducibility_note": (
                "model_config block records the exact dependency matrix, sector weights, "
                "and thresholds active during this experiment. "
                f"Full snapshot: {model_config['matrix_snapshot_path']}"
            ),
        },
        "artifact_files": {
            "full_json": str(full_path),
            "runs_csv": str(csv_path),
            "metadata": str(meta_path),
        },
    }

    with open(meta_path, "w") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)
    print(f"[save] meta JSON → {meta_path}")

    return {"full": full_path, "csv": csv_path, "meta": meta_path}


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args():
    p = argparse.ArgumentParser(
        description="Run a Monte Carlo experiment and save reproducible artifacts.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    p.add_argument("--scenario", default="S1_energy_outage", help="scenario_id")
    p.add_argument("--sector", default="energy", help="initiator sector")
    p.add_argument("--runs", type=int, default=100, help="number of MC runs")
    p.add_argument("--duration-min", type=int, default=5, dest="duration_min")
    p.add_argument("--duration-max", type=int, default=30, dest="duration_max")
    p.add_argument("--initiator-action", default="outage", dest="initiator_action")
    p.add_argument("--theta-classical", type=float, default=0.3, dest="theta_classical",
                   help="cascade detection threshold")
    p.add_argument("--theta-node", type=float, default=None, dest="theta_node",
                   help="Override theta_node (binarisation threshold) on risk_engine for this run")
    p.add_argument("--stochastic-scale", type=float, default=0.3, dest="stochastic_scale")
    p.add_argument("--mode", default="real", choices=["real", "quantum"])
    p.add_argument("--load-amount", type=float, default=0.25, dest="load_amount",
                   help="Load increase amount (used with --initiator-action=load_increase)")
    p.add_argument("--prefix", default=None,
                   help="Output file prefix (e.g. results/mc_s1_100). "
                        "Defaults to results/mc_<scenario>_<runs>.")

    # Realism extensions
    p.add_argument("--weather-factor", type=float, default=1.0, dest="weather_factor")
    p.add_argument("--load-factor", type=float, default=1.0, dest="load_factor")
    p.add_argument("--fuel-stress-factor", type=float, default=1.0, dest="fuel_stress_factor")
    p.add_argument("--heterogeneity-scale", type=float, default=0.0, dest="heterogeneity_scale")
    p.add_argument("--propagation-depth", type=int, default=1, dest="propagation_depth")
    p.add_argument("--enable-recovery", action="store_true", dest="enable_recovery")
    p.add_argument("--recovery-rate", type=float, default=0.2, dest="recovery_rate")
    p.add_argument("--recovery-horizon", type=int, default=5, dest="recovery_horizon")

    # Infrastructure
    p.add_argument("--simulator-url", default=SIMULATOR_URL, dest="simulator_url")
    p.add_argument("--risk-engine-url", default=RISK_ENGINE_URL, dest="risk_engine_url")
    p.add_argument("--snapshot-path", default=str(SNAPSHOT_PATH), dest="snapshot_path",
                   help="Path to dependency_matrix_live_snapshot.json")
    p.add_argument("--force-refresh-snapshot", action="store_true", dest="force_refresh",
                   help="Re-fetch snapshot from live risk_engine even if file exists")

    return p.parse_args()


def main():
    args = parse_args()

    snapshot_path = Path(args.snapshot_path)
    global RISK_ENGINE_URL
    RISK_ENGINE_URL = args.risk_engine_url

    # Step 1: Load or create snapshot
    snapshot = load_or_create_snapshot(snapshot_path, force_refresh=args.force_refresh)
    model_config = build_model_config(snapshot, snapshot_path)

    print(f"[model] matrix version={model_config['matrix_version']}  "
          f"theta_bin={model_config['theta_bin']}  "
          f"theta_cascade={model_config['theta_cascade']}")

    # Step 2: Build request payload
    payload: dict = {
        "scenario_id": args.scenario,
        "sector": args.sector,
        "runs": args.runs,
        "duration_min": args.duration_min,
        "duration_max": args.duration_max,
        "initiator_action": args.initiator_action,
        "load_amount": args.load_amount,
        "theta_classical": args.theta_classical,
        "stochastic_scale": args.stochastic_scale,
        "mode": args.mode,
    }
    if args.theta_node is not None:
        payload["theta_node"] = args.theta_node

    # Only include non-default realism params to keep payload minimal
    if args.weather_factor != 1.0:
        payload["weather_factor"] = args.weather_factor
    if args.load_factor != 1.0:
        payload["load_factor"] = args.load_factor
    if args.fuel_stress_factor != 1.0:
        payload["fuel_stress_factor"] = args.fuel_stress_factor
    if args.heterogeneity_scale != 0.0:
        payload["heterogeneity_scale"] = args.heterogeneity_scale
    if args.propagation_depth != 1:
        payload["propagation_depth"] = args.propagation_depth
    if args.enable_recovery:
        payload["enable_recovery"] = True
        payload["recovery_rate"] = args.recovery_rate
        payload["recovery_horizon"] = args.recovery_horizon

    # Step 3: Run experiment
    t0 = time.monotonic()
    try:
        result = run_mc(payload, args.simulator_url)
    except httpx.HTTPStatusError as e:
        print(f"[error] HTTP {e.response.status_code}: {e.response.text[:500]}", file=sys.stderr)
        sys.exit(1)
    except httpx.RequestError as e:
        print(f"[error] Connection failed: {e}", file=sys.stderr)
        sys.exit(1)
    elapsed = time.monotonic() - t0
    print(f"[mc] Done in {elapsed:.1f}s  K_cl={result.get('K_cl')}  K_q={result.get('K_q')}")

    # Step 4: Save artifacts
    prefix = args.prefix or f"results/mc_{args.scenario}_{args.runs}"
    save_artifacts(
        result=result,
        model_config=model_config,
        request_payload=payload,
        prefix=prefix,
        elapsed=elapsed,
        simulator_url=args.simulator_url,
    )

    print("[done] Experiment complete.")


if __name__ == "__main__":
    main()
